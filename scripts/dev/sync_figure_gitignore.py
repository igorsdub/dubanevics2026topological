"""Regenerate the manuscript-figure block of .gitignore from config/manuscript.toml.

Only canonical PNGs that a non-external, non-planned ``[[figure]]`` entry names
by ``source`` are tracked; everything else under ``output/figures/canonical/``
(titled twins, unreferenced renders, JSON sidecars) stays local.

The same holds for tables in a second block: the canonical exports (csv, html,
md, json sidecar) that a non-planned ``[[table]]`` entry names by ``source`` are
tracked, as are the numbered ``main/`` and ``supplementary/`` copies and their
``manifest.csv``; other exports under ``output/tables/canonical/`` stay local.

    python scripts/dev/sync_figure_gitignore.py          # rewrite the block
    python scripts/dev/sync_figure_gitignore.py --check  # exit 1 if out of sync
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANUSCRIPT = ROOT / "config" / "manuscript.toml"
GITIGNORE = ROOT / ".gitignore"
BEGIN = "# BEGIN manuscript figures (generated by scripts/dev/sync_figure_gitignore.py)"
END = "# END manuscript figures (generated by scripts/dev/sync_figure_gitignore.py)"
CANONICAL = "output/figures/canonical"
TABLE_BEGIN = "# BEGIN manuscript tables (generated by scripts/dev/sync_figure_gitignore.py)"
TABLE_END = "# END manuscript tables (generated by scripts/dev/sync_figure_gitignore.py)"
TABLE_CANONICAL = "output/tables/canonical"
TABLE_EXTENSIONS = ("csv", "html", "md", "json")


def referenced_stems(manuscript: Path = MANUSCRIPT) -> list[str]:
    """Return the sorted canonical stems of built, non-external manuscript figures."""
    data = tomllib.loads(manuscript.read_text(encoding="utf-8"))
    stems = {
        entry["source"]
        for entry in data.get("figure", [])
        if entry.get("source")
        and not entry.get("external")
        and entry.get("status") != "planned"
    }
    return sorted(stems)


def _escape(name: str) -> str:
    return re.sub(r"([\\*?\[\]])", r"\\\1", name)


def render_block(stems: list[str]) -> str:
    """Return the full marked block, without a trailing newline."""
    lines = [
        BEGIN,
        "# Edit config/manuscript.toml, then run the script; never edit this block by hand.",
        f"!{CANONICAL}/",
        f"{CANONICAL}/*",
        f"!{CANONICAL}/README.md",
        *(f"!{CANONICAL}/{_escape(stem)}.png" for stem in stems),
        END,
    ]
    return "\n".join(lines)


def referenced_table_stems(manuscript: Path = MANUSCRIPT) -> list[str]:
    """Return the sorted canonical stems of built manuscript tables."""
    data = tomllib.loads(manuscript.read_text(encoding="utf-8"))
    stems = {
        entry["source"]
        for entry in data.get("table", [])
        if entry.get("source") and entry.get("status") != "planned"
    }
    return sorted(stems)


def render_table_block(stems: list[str]) -> str:
    """Return the full marked table block, without a trailing newline."""
    lines = [
        TABLE_BEGIN,
        "# Edit config/manuscript.toml, then run the script; never edit this block by hand.",
        f"!{TABLE_CANONICAL}/",
        f"{TABLE_CANONICAL}/*",
        f"!{TABLE_CANONICAL}/README.md",
        *(
            f"!{TABLE_CANONICAL}/{_escape(stem)}.{extension}"
            for stem in stems
            for extension in TABLE_EXTENSIONS
        ),
        "!output/tables/main/",
        "!output/tables/supplementary/",
        "!output/tables/manifest.csv",
        TABLE_END,
    ]
    return "\n".join(lines)


def synced_text(current: str, block: str, begin: str = BEGIN, end: str = END) -> str:
    """Return ``current`` with the marked block replaced by ``block``."""
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
    if not pattern.search(current):
        raise SystemExit(f"{GITIGNORE}: marker block not found")
    return pattern.sub(lambda _m: block, current, count=1)


def main(argv: list[str]) -> int:
    current = GITIGNORE.read_text(encoding="utf-8")
    wanted = synced_text(current, render_block(referenced_stems()))
    wanted = synced_text(
        wanted, render_table_block(referenced_table_stems()), TABLE_BEGIN, TABLE_END
    )
    if "--check" in argv:
        if wanted != current:
            print(
                ".gitignore manuscript block is out of sync; run "
                "python scripts/dev/sync_figure_gitignore.py",
                file=sys.stderr,
            )
            return 1
        return 0
    if wanted != current:
        GITIGNORE.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
